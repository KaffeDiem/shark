/// Theme families for Settings, each a dark and a light `ThemeConfig` named `<family> Dark/Light`.
/// Linear is hand-tuned; the others are generated by `docs/themes.py`.
const THEMES: &[(&str, &str)] = &[
    ("Linear", include_str!("../assets/themes/linear.json")),
    ("Roraima", include_str!("../assets/themes/roraima.json")),
    ("Everest", include_str!("../assets/themes/everest.json")),
    ("Sequoia", include_str!("../assets/themes/sequoia.json")),
    ("Sakura", include_str!("../assets/themes/sakura.json")),
];

fn theme_configs() -> Vec<ThemeConfig> {
    THEMES
        .iter()
        .flat_map(|(name, json)| {
            serde_json::from_str::<ThemeSet>(json)
                .unwrap_or_else(|e| panic!("{name} theme: {e}"))
                .themes
        })
        .collect()
}

/// Installs the saved light and dark themes, with the font overrides baked in so a
/// mode switch (which reloads the config) keeps them, then picks the mode.
pub fn apply(a: &Appearance, cx: &mut App) {
    let registry = ThemeRegistry::global(cx);
    let stock = [
        registry.default_dark_theme().highlight.clone(),
        registry.default_light_theme().highlight.clone(),
    ];
    let configs = theme_configs();
    let pick = |family: &str, mode: ThemeMode| {
        let suffix = if mode.is_dark() { "Dark" } else { "Light" };
        let mut t = [family, "Linear"]
            .iter()
            .find_map(|f| {
                let name = format!("{f} {suffix}");
                configs.iter().find(|t| t.name.as_ref() == name)
            })
            .expect("Linear theme")
            .clone();
        // Syntax colors aren't restyled; borrow the stock ones of the same mode.
        t.highlight = stock[!mode.is_dark() as usize].clone();
        if let Some(f) = &a.ui_font {
            t.font_family = Some(f.clone().into());
        }
        if let Some(f) = &a.mono_font {
            t.mono_font_family = Some(f.clone().into());
        }
        Rc::new(t)
    };
    let (dark, light) = (
        pick(&a.dark, ThemeMode::Dark),
        pick(&a.light, ThemeMode::Light),
    );
    Theme::update(cx, |t| {
        t.dark_theme = dark;
        t.light_theme = light;
    });
    let mode = match a.mode {
        Mode::System => cx.window_appearance().into(),
        Mode::Light => ThemeMode::Light,
        Mode::Dark => ThemeMode::Dark,
    };
    Theme::change(mode, None, cx);
}

pub fn open(state: &State, window: &mut Window, cx: &mut Context<Shark>) {
    let shark = cx.entity().downgrade();
    let view = cx.new(|cx| Settings::new(shark, state, window, cx));
    let focus = view.read(cx).focus.clone();
    window.open_dialog(cx, move |d, _, _| {
        // No dialog title: the page list and the page title say where you are.
        d.font_features(inter_features())
            .w(px(800.))
            .child(view.clone())
    });
    focus.focus(window, cx);
}

/// About dialog (Shark > About Shark): version, author, license and repo link.
pub fn about(window: &mut Window, cx: &mut App) {
    window.open_dialog(cx, |d, _, cx| {
        d.font_features(inter_features())
            .title("Shark")
            .w(px(640.))
            .child(
                v_flex()
                    .gap_1()
                    .child(format!("Version {}", env!("CARGO_PKG_VERSION")))
                    .child("Shark by Kasper Munch Jensen")
                    .child(
                        div()
                            .text_color(cx.theme().muted_foreground)
                            .child("GPL-3.0"),
                    )
                    .child(
                        Link::new("about-repo")
                            .href("https://github.com/KaffeDiem/shark")
                            .child("github.com/KaffeDiem/shark"),
                    ),
            )
    });
}

type Choice = Entity<SelectState<SearchableVec<SharedString>>>;

pub struct Settings {
    shark: WeakEntity<Shark>,
    tab: usize,
    focus: FocusHandle,
    light: Choice,
    dark: Choice,
    ui_font: Choice,
    mono_font: Choice,
    prompts: Vec<Entity<TextareaState>>,
    _subs: Vec<Subscription>,
}

const DEFAULT_UI: &str = "Default (Inter)";
const DEFAULT_MONO: &str = "Default (JetBrains Mono NL)";

impl Settings {
    pub(crate) fn new(
        shark: WeakEntity<Shark>,
        state: &State,
        window: &mut Window,
        cx: &mut Context<Self>,
    ) -> Self {
        let a = &state.appearance;
        let mut fonts: Vec<String> = cx
            .text_system()
            .all_font_names()
            .into_iter()
            .filter(|f| !f.starts_with('.'))
            .collect();
        fonts.sort_by_key(|f| f.to_lowercase());
        fonts.dedup();
        let families: Vec<SharedString> = THEMES.iter().map(|(n, _)| (*n).into()).collect();
        let mut choice = |items: Vec<SharedString>, current: &str, searchable: bool| {
            let ix = items
                .iter()
                .position(|i| i.as_ref() == current)
                .unwrap_or(0);
            cx.new(|cx| {
                SelectState::new(
                    SearchableVec::new(items),
                    Some(IndexPath::new(ix)),
                    window,
                    cx,
                )
                .searchable(searchable)
            })
        };
        let font_items = |default: &str| {
            std::iter::once(default.to_string())
                .chain(fonts.iter().cloned())
                .map(SharedString::from)
                .collect::<Vec<_>>()
        };
        let light = choice(families.clone(), &a.light, false);
        let dark = choice(families, &a.dark, false);
        let ui_font = choice(
            font_items(DEFAULT_UI),
            a.ui_font.as_deref().unwrap_or(DEFAULT_UI),
            true,
        );
        let mono_font = choice(
            font_items(DEFAULT_MONO),
            a.mono_font.as_deref().unwrap_or(DEFAULT_MONO),
            true,
        );

        let mut subs = vec![];
        let on_pick = |set: fn(&mut Appearance, Option<String>)| {
            move |this: &mut Self,
                  _: &Choice,
                  ev: &SelectEvent<SearchableVec<SharedString>>,
                  _: &mut Window,
                  cx: &mut Context<Self>| {
                let SelectEvent::Confirm(Some(v)) = ev else {
                    return;
                };
                let v = Some(v.to_string()).filter(|v| !v.starts_with("Default ("));
                this.appearance(cx, |a| set(a, v));
            }
        };
        subs.push(cx.subscribe_in(
            &light,
            window,
            on_pick(|a, v| a.light = v.unwrap_or_default()),
        ));
        subs.push(cx.subscribe_in(
            &dark,
            window,
            on_pick(|a, v| a.dark = v.unwrap_or_default()),
        ));
        subs.push(cx.subscribe_in(&ui_font, window, on_pick(|a, v| a.ui_font = v)));
        subs.push(cx.subscribe_in(&mono_font, window, on_pick(|a, v| a.mono_font = v)));

        let prompts = PROMPTS
            .iter()
            .enumerate()
            .map(|(i, p)| {
                let text = prompts::get(p.id);
                // ponytail: auto_grow counts newlines, not wrapped lines; ~60 mono chars fit a row,
                // plus one spare so the last line is never cut.
                let rows = (text.len() / 60 + 2).clamp(3, 12);
                let ta = cx.new(|cx| {
                    TextareaState::new(window, cx)
                        .auto_grow(rows, 14)
                        .default_value(text)
                });
                subs.push(cx.subscribe_in(&ta, window, move |this, ta, ev, _, cx| {
                    if let InputEvent::Change = ev {
                        let text = ta.read(cx).value().to_string();
                        this.set_prompt(i, Some(text), cx);
                    }
                }));
                ta
            })
            .collect();

        Settings {
            shark,
            tab: 0,
            focus: cx.focus_handle(),
            light,
            dark,
            ui_font,
            mono_font,
            prompts,
            _subs: subs,
        }
    }

    fn with_state<R>(&self, cx: &mut App, f: impl FnOnce(&mut State) -> R) -> Option<R> {
        self.shark
            .update(cx, |s, _| {
                let r = f(&mut s.state);
                s.state.save();
                r
            })
            .ok()
    }

    pub(crate) fn appearance(&mut self, cx: &mut Context<Self>, f: impl FnOnce(&mut Appearance)) {
        if let Some(a) = self.with_state(cx, |s| {
            f(&mut s.appearance);
            s.appearance.clone()
        }) {
            apply(&a, cx);
        }
        cx.notify();
    }

    fn set_stay_awake(&mut self, on: bool, cx: &mut Context<Self>) {
        self.shark
            .update(cx, |s, cx| {
                s.state.stay_awake = on;
                s.state.save();
                s.update_awake(cx);
            })
            .ok();
        cx.notify();
    }

    pub(crate) fn set_vim(&mut self, on: bool, cx: &mut Context<Self>) {
        self.shark.update(cx, |s, cx| s.set_vim(on, cx)).ok();
        cx.notify();
    }

    /// `None` or the default text drops the override.
    pub(crate) fn set_prompt(&mut self, i: usize, text: Option<String>, cx: &mut Context<Self>) {
        let p = &PROMPTS[i];
        let text = text.filter(|t| t != p.default);
        self.with_state(cx, |s| {
            match text {
                Some(t) => s.prompts.insert(p.id.into(), t),
                None => s.prompts.remove(p.id),
            };
            prompts::set_overrides(&s.prompts);
        });
        cx.notify();
    }

    pub(crate) fn reset_prompt(&mut self, i: usize, window: &mut Window, cx: &mut Context<Self>) {
        self.prompts[i].update(cx, |t, cx| t.set_value(PROMPTS[i].default, window, cx));
        self.set_prompt(i, None, cx);
    }

    fn mode(&self, cx: &App) -> Mode {
        self.shark
            .upgrade()
            .map(|s| s.read(cx).state.appearance.mode)
            .unwrap_or_default()
    }

    fn render_general(&self, cx: &mut Context<Self>) -> impl IntoElement {
        let (awake, vim) = (self.shark.upgrade())
            .map(|s| (s.read(cx).state.stay_awake, s.read(cx).state.vim))
            .unwrap_or_default();
        let this = cx.entity().downgrade();
        let theme = cx.theme();
        card(theme)
            .child(row(
                theme,
                false,
                "Stay awake while agents run",
                "The Mac doesn't idle-sleep mid-turn; the display may still turn off",
                Switch::new("stay-awake").checked(awake).on_click({
                    let this = this.clone();
                    move |&v, _, cx| {
                        this.update(cx, |s, cx| s.set_stay_awake(v, cx)).ok();
                    }
                }),
            ))
            .child(row(
                theme,
                true,
                "Vim mode",
                "Vim keys in the file editor, the composer and lists (ctrl-cmd-v)",
                Switch::new("vim").checked(vim).on_click(move |&v, _, cx| {
                    this.update(cx, |s, cx| s.set_vim(v, cx)).ok();
                }),
            ))
    }

    fn render_appearance(&self, cx: &mut Context<Self>) -> impl IntoElement {
        let mode = self.mode(cx);
        let theme = cx.theme();
        let modes = [
            (Mode::System, "System", IconName::Monitor),
            (Mode::Light, "Light", IconName::Sun),
            (Mode::Dark, "Dark", IconName::Moon),
        ];
        let mode_group = h_flex()
            .gap_1()
            .children(modes.iter().map(|(m, label, icon)| {
                let m = *m;
                pill(label, Some(*icon), m == mode).on_click(
                    cx.listener(move |this, _, _, cx| this.appearance(cx, |a| a.mode = m)),
                )
            }));
        let sample = div()
            .px_3()
            .py_2()
            .rounded(theme.radius)
            .bg(theme.muted)
            .font_family(theme.mono_font_family.clone())
            .text_size(theme.mono_font_size)
            .text_color(theme.foreground)
            .child("let id = 0x1Il0O; // git push -u origin main");
        v_flex()
            .gap_3()
            .child(section(theme, "Theme"))
            .child(
                card(theme)
                    .child(row(
                        theme,
                        false,
                        "Mode",
                        "System follows macOS",
                        mode_group,
                    ))
                    .child(row(
                        theme,
                        true,
                        "Light theme",
                        "Used in light mode",
                        Select::new(&self.light).small(),
                    ))
                    .child(row(
                        theme,
                        true,
                        "Dark theme",
                        "Used in dark mode",
                        Select::new(&self.dark).small(),
                    )),
            )
            .child(section(theme, "Fonts"))
            .child(
                card(theme)
                    .child(row(
                        theme,
                        false,
                        "Interface font",
                        "Sidebar, transcript and menus",
                        Select::new(&self.ui_font).small().menu_max_h(px(320.)),
                    ))
                    .child(row(
                        theme,
                        true,
                        "Code font",
                        "Code, diffs and tool output",
                        Select::new(&self.mono_font).small().menu_max_h(px(320.)),
                    ))
                    .child(
                        div()
                            .p_3()
                            .border_t_1()
                            .border_color(theme.border)
                            .child(sample),
                    ),
            )
    }

    fn render_prompts(&self, cx: &mut Context<Self>) -> impl IntoElement {
        let theme = cx.theme();
        let (mono, mono_size, hint) = (
            theme.mono_font_family.clone(),
            theme.mono_font_size,
            faint(theme),
        );
        let (border, radius, muted_fg, secondary) = (
            theme.border,
            theme.radius,
            theme.muted_foreground,
            theme.secondary,
        );
        let edited: Vec<bool> = PROMPTS
            .iter()
            .map(|p| prompts::get(p.id) != p.default)
            .collect();
        v_flex()
            .gap_4()
            .children(PROMPTS.iter().enumerate().map(|(i, p)| {
                v_flex()
                    .gap_1p5()
                    .child(
                        h_flex()
                            .h(px(24.))
                            .gap_2()
                            .child(
                                div()
                                    .text_sm()
                                    .font_weight(FontWeight::MEDIUM)
                                    .child(p.title),
                            )
                            .when(edited[i], |r| {
                                r.child(div().text_xs().text_color(muted_fg).child("Edited"))
                            })
                            .child(div().flex_1())
                            .when(edited[i], |r| {
                                r.child(
                                    Button::new(("reset", i))
                                        .ghost()
                                        .xsmall()
                                        .icon(IconName::RotateCcw)
                                        .label("Reset to default")
                                        .on_click(cx.listener(move |this, _, w, cx| {
                                            this.reset_prompt(i, w, cx)
                                        })),
                                )
                            }),
                    )
                    .child(
                        div()
                            .rounded(radius)
                            .border_1()
                            .border_color(border)
                            .bg(secondary)
                            .font_family(mono.clone())
                            .text_size(mono_size)
                            .child(Textarea::new(&self.prompts[i]).appearance(false)),
                    )
                    .child(
                        div()
                            .text_xs()
                            .text_color(hint)
                            .child(format!("{{repos}}: {}", p.repos)),
                    )
            }))
    }
}

/// Settings pages: nav icon, then title and the one line under it.
const PAGES: &[(IconName, (&str, &str))] = &[
    (
        IconName::Settings,
        ("General", "How Shark behaves while it works"),
    ),
    (
        IconName::Palette,
        ("Appearance", "Themes and fonts, applied as you pick them"),
    ),
    (
        IconName::MessageSquareText,
        (
            "Prompts",
            "Sent to the agent by the git button; {repos} and {branch} are filled in when the step runs",
        ),
    ),
];

/// A ghost button that shows its selection, so tabs and mode are tab stops with enter/space.
fn pill(label: &'static str, icon: Option<IconName>, active: bool) -> Button {
    Button::new(label)
        .ghost()
        .small()
        .label(label)
        .when_some(icon, |b, i| b.icon(i))
        .selected(active)
}

fn section(theme: &Theme, label: &'static str) -> impl IntoElement {
    div()
        .text_xs()
        .text_color(theme.muted_foreground)
        .font_weight(FontWeight::MEDIUM)
        .child(label)
}

fn card(theme: &Theme) -> Div {
    v_flex()
        .rounded(theme.radius_lg)
        .border_1()
        .border_color(theme.border)
        .bg(theme.secondary)
}

/// Label and description on the left, the control on the right (Linear's settings rows).
fn row(
    theme: &Theme,
    sep: bool,
    label: &'static str,
    desc: &'static str,
    control: impl IntoElement,
) -> impl IntoElement {
    h_flex()
        .min_h(px(52.))
        .px_3()
        .gap_3()
        .when(sep, |r| r.border_t_1().border_color(theme.border))
        .child(
            v_flex().flex_1().child(div().text_sm().child(label)).child(
                div()
                    .text_xs()
                    .text_color(theme.muted_foreground)
                    .child(desc),
            ),
        )
        .child(div().w(px(240.)).flex().justify_end().child(control))
}

impl Render for Settings {
    fn render(&mut self, _: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let body = match self.tab {
            0 => self.render_general(cx).into_any_element(),
            1 => self.render_appearance(cx).into_any_element(),
            _ => self.render_prompts(cx).into_any_element(),
        };
        let (title, desc) = PAGES[self.tab].1;
        let theme = cx.theme();
        // A page list on the left, the page on the right (FLORA, Teams, Braintrust on Mobbin).
        h_flex()
            .key_context("Settings")
            .track_focus(&self.focus)
            .items_start()
            .gap_6()
            .on_action(cx.listener(|this, _: &SwitchField, _, cx| {
                this.tab = (this.tab + 1) % PAGES.len();
                cx.notify();
            }))
            .child(v_flex().w(px(168.)).flex_none().gap_0p5().children(
                PAGES.iter().enumerate().map(|(i, (icon, (label, _)))| {
                    let on = i == self.tab;
                    // Rows, not buttons: a Button centres its content, so the icons wouldn't line up.
                    h_flex()
                        .id(*label)
                        .h(px(28.))
                        .px_2()
                        .gap_2()
                        .rounded(theme.radius)
                        .text_sm()
                        .text_color(if on { theme.foreground } else { theme.muted_foreground })
                        .when(on, |d| d.bg(theme.accent))
                        .when(!on, |d| d.hover(|d| d.bg(theme.secondary_hover)))
                        .child(gpui_kit::component::Icon::new(icon.clone()).with_size(px(14.)))
                        .child(*label)
                        .on_click(cx.listener(move |this, _, _, cx| {
                            this.tab = i;
                            cx.notify();
                        }))
                }),
            ))
            .child(
                // A fixed height, so switching pages doesn't move the dialog; long pages scroll.
                v_flex()
                    .id("settings-page")
                    .flex_1()
                    .min_w_0()
                    .h(px(520.))
                    .overflow_y_scroll()
                    .gap_4()
                    .child(
                        v_flex()
                            .gap_0p5()
                            .child(
                                div()
                                    .text_base()
                                    .font_weight(FontWeight::SEMIBOLD)
                                    .child(title),
                            )
                            .child(
                                div()
                                    .text_xs()
                                    .text_color(theme.muted_foreground)
                                    .child(desc),
                            ),
                    )
                    .child(body),
            )
    }
}

#[cfg(test)]
mod tests {
    use gpui_kit::component::ThemeMode;

    /// A typo in a key is silently ignored by serde, so check values that matter actually land.
    #[test]
    fn themes_parse() {
        let themes = super::theme_configs();
        for (i, (family, _)) in super::THEMES.iter().enumerate() {
            let pair = &themes[i * 2..i * 2 + 2];
            assert_eq!(pair[0].mode, ThemeMode::Dark, "{family}");
            assert_eq!(pair[1].mode, ThemeMode::Light, "{family}");
            assert_eq!(pair[0].name.as_ref(), format!("{family} Dark"));
            assert_eq!(pair[1].name.as_ref(), format!("{family} Light"));
        }
        for t in &themes {
            let c = &t.colors;
            for key in [
                &c.background,
                &c.foreground,
                &c.muted_foreground,
                &c.sidebar,
                &c.primary,
                &c.link,
            ] {
                assert!(key.is_some(), "{} is missing a core color", t.name);
            }
            assert_eq!(t.font_family.as_deref(), Some("Inter"));
        }
    }
}
